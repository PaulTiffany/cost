"""
result_provenance_check.py — L15 source-JSON provenance verifier.

For every unique source_file referenced in ci/claim_data_ties.json (L15),
this script loads the JSON, classifies it into one of three buckets, and
verifies that the required provenance fields are present.

Buckets
-------
deterministic
    Source lives in supplementary/experiments/ AND contains structured data
    tables (model -> {results: [...]}, trials, etc.).
    Required: _meta.generator_script OR top-level "experiment" key,
              _meta.parameters OR top-level "meta.n_trials" / "parameters",
              and ideally _meta.script_hash (sha256 of the generator).

api_generated
    Source filename contains any of: openrouter, cross_model, blinded,
    image_transfer, high_k_opus; OR top-level has model_id / model key
    AND a timestamp.
    Required: model list (_meta.model_list OR .models OR top-level "models"),
              trial count (_meta.n_trials OR top-level "n_trials" OR derivable
              from "total_results"),
              timestamp (_meta.started_iso OR .run_date OR top-level
              "timestamp").

allowlisted
    File is in WHITELIST below with a stated reason.
    Required: entry exists in WHITELIST dict.

Design intent: be lenient on the FIRST pass — missing fields are surfaced as
warnings, not hard failures, unless the file is completely unclassifiable.
Files that are fully unclassifiable AND not allowlisted cause EXIT 1.

Exit codes: 0 = all pass, 1 = one or more failures, 2 = invocation error.
"""

