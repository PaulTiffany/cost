# ---------------------------------------------------------------------------
# API-generated filename keywords (any match -> api_generated bucket)
# ---------------------------------------------------------------------------
API_KEYWORDS = [
    "openrouter",
    "cross_model",
    "blinded",
    "image_transfer",
    "high_k",
    "policy_density",
    "implicit_k",
]


# ---------------------------------------------------------------------------
# Classification logic
# ---------------------------------------------------------------------------

def _has_key_path(d: Any, *keys: str) -> bool:
    """Return True if the nested key path exists and is not None/empty."""
    node = d
    for k in keys:
        if not isinstance(node, dict) or k not in node:
            return False
        node = node[k]
    return node is not None and node != "" and node != []


def classify(rel_path: str, data: dict) -> str:
    """Return 'deterministic', 'api_generated', or 'allowlisted_or_unknown'."""
    if rel_path in WHITELIST:
        return "allowlisted"

    fname = Path(rel_path).name.lower()
    rel_lower = rel_path.lower().replace("\\", "/")

    # API-generated heuristic: filename keyword OR model_id present at top level
    if any(kw in fname for kw in API_KEYWORDS):
        return "api_generated"
    if any(kw in rel_lower for kw in API_KEYWORDS):
        return "api_generated"
    if "model_id" in data or (
        isinstance(data.get("results"), list)
        and data["results"]
        and "model_id" in data["results"][0]
    ):
        return "api_generated"

    # Deterministic heuristic: lives in supplementary/experiments/ AND has
    # structured experiment metadata
    in_supp = rel_lower.startswith("supplementary/experiments/")
    has_experiment_key = (
        "experiment" in data
        or _has_key_path(data, "meta", "experiment")
        or _has_key_path(data, "_meta", "experiment")
    )
    if in_supp and has_experiment_key:
        return "deterministic"
    if in_supp:
        return "deterministic"

    return "allowlisted_or_unknown"


# ---------------------------------------------------------------------------
# Field verification per bucket
# ---------------------------------------------------------------------------

def check_deterministic(rel_path: str, data: dict) -> list[str]:
    """Return list of missing field names for a deterministic source."""
    missing = []

    # generator_script — accept: _meta.generator_script, top-level "experiment",
    # meta.experiment
    has_script = (
        _has_key_path(data, "_meta", "generator_script")
        or _has_key_path(data, "experiment")
        or _has_key_path(data, "meta", "experiment")
    )
    if not has_script:
        missing.append("_meta.generator_script (or top-level 'experiment'/'meta.experiment')")

    # parameters — accept: _meta.parameters, meta.n_trials, top-level "parameters"
    has_params = (
        _has_key_path(data, "_meta", "parameters")
        or _has_key_path(data, "parameters")
        or _has_key_path(data, "meta", "n_trials")
        or _has_key_path(data, "_meta", "n_trials_per_task")
    )
    if not has_params:
        missing.append("_meta.parameters (or 'parameters'/'meta.n_trials')")

    # script_hash is advisory — flag as advisory not failure
    has_hash = _has_key_path(data, "_meta", "script_hash")
    if not has_hash:
        missing.append("ADVISORY: _meta.script_hash (sha256 of generator; enables bitwise reproducibility check)")

    return missing


def check_api_generated(rel_path: str, data: dict) -> list[str]:
    """Return list of missing field names for an api_generated source."""
    missing = []

    # model list
    has_models = (
        _has_key_path(data, "_meta", "model_list")
        or _has_key_path(data, "_meta", "models")
        or _has_key_path(data, "models")
        or _has_key_path(data, "_meta", "model")
        or _has_key_path(data, "model")
    )
    if not has_models:
        missing.append("_meta.model_list / .models / top-level 'models' or 'model'")

    # trial count
    has_trials = (
        _has_key_path(data, "_meta", "n_trials")
        or _has_key_path(data, "n_trials")
        or _has_key_path(data, "total_results")
        or _has_key_path(data, "_meta", "n_images")
        or _has_key_path(data, "n_trials_per_cell")
        # derivable: if results list exists, length IS the trial count
        or (isinstance(data.get("results"), list) and len(data["results"]) > 0)
    )
    if not has_trials:
        missing.append("_meta.n_trials / top-level 'n_trials', 'n_trials_per_cell', 'total_results', or non-empty 'results' list")

    # timestamp
    has_ts = (
        _has_key_path(data, "_meta", "started_iso")
        or _has_key_path(data, "_meta", "run_date")
        or _has_key_path(data, "timestamp")
        or _has_key_path(data, "analysis_timestamp")
        or _has_key_path(data, "_meta", "timestamp")
        or _has_key_path(data, "date")
    )
    if not has_ts:
        missing.append("_meta.started_iso / _meta.run_date / top-level 'timestamp' or 'date'")

    return missing


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> int:
    if not CLAIM_DATA_TIES.exists():
        print(f"ERROR: claim_data_ties.json not found at {CLAIM_DATA_TIES}", file=sys.stderr)
        return 2

    with CLAIM_DATA_TIES.open(encoding="utf-8") as fh:
        ties = json.load(fh)

    claims = ties.get("claims", {})
    if not claims:
        print("ERROR: 'claims' key missing or empty in claim_data_ties.json", file=sys.stderr)
        return 2

    # Collect unique source files
    source_files: set[str] = set()
    for claim in claims.values():
        sf = claim.get("source_file")
        if sf:
            source_files.add(sf)

    per_source: list[dict] = []
    bucket_counts: dict[str, int] = {"deterministic": 0, "api_generated": 0, "allowlisted": 0}
    passed = 0
    failed = 0

    for rel_path in sorted(source_files):
        abs_path = REPO_ROOT / rel_path.replace("/", "\\")
        entry: dict = {"path": rel_path, "bucket": None, "passed": False, "missing_fields": []}

        if not abs_path.exists():
            entry["bucket"] = "missing_file"
            entry["passed"] = False
            entry["missing_fields"] = ["FILE_NOT_FOUND"]
            failed += 1
            per_source.append(entry)
            continue

        try:
            with abs_path.open(encoding="utf-8") as fh:
                data = json.load(fh)
        except Exception as exc:
            entry["bucket"] = "parse_error"
            entry["passed"] = False
            entry["missing_fields"] = [f"JSON_PARSE_ERROR: {exc}"]
            failed += 1
            per_source.append(entry)
            continue

        bucket = classify(rel_path, data)
        entry["bucket"] = bucket

        if bucket == "allowlisted":
            entry["passed"] = True
            entry["allowlist_reason"] = WHITELIST[rel_path]["reason"]
            bucket_counts["allowlisted"] += 1
            passed += 1

        elif bucket == "deterministic":
            missing = check_deterministic(rel_path, data)
            # Advisory fields do not cause failure
            hard_missing = [m for m in missing if not m.startswith("ADVISORY")]
            advisory = [m for m in missing if m.startswith("ADVISORY")]
            entry["missing_fields"] = missing
            if hard_missing:
                entry["passed"] = False
                failed += 1
            else:
                entry["passed"] = True
                passed += 1
            if advisory:
                entry["advisory"] = advisory
            bucket_counts["deterministic"] += 1

        elif bucket == "api_generated":
            missing = check_api_generated(rel_path, data)
            entry["missing_fields"] = missing
            if missing:
                entry["passed"] = False
                failed += 1
            else:
                entry["passed"] = True
                passed += 1
            bucket_counts["api_generated"] += 1

        else:  # allowlisted_or_unknown
            entry["passed"] = False
            entry["missing_fields"] = [
                "UNCLASSIFIED: not in WHITELIST and heuristics could not assign a bucket. "
                "Add to WHITELIST with a reason, or add _meta fields to enable classification."
            ]
            failed += 1

        per_source.append(entry)

    total = len(per_source)
    summary = {
        "total_sources": total,
        "passed": passed,
        "failed": failed,
        "buckets": bucket_counts,
    }

    result = {"summary": summary, "per_source": per_source}

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT_FILE.open("w", encoding="utf-8") as fh:
        json.dump(result, fh, indent=2)

    # Print human-readable summary
    print(f"L15 provenance check: {total} sources | {passed} PASS | {failed} FAIL")
    print(
        f"Buckets: deterministic={bucket_counts['deterministic']} "
        f"api_generated={bucket_counts['api_generated']} "
        f"allowlisted={bucket_counts['allowlisted']}"
    )
    print(f"Results written to: {OUTPUT_FILE}")

    if failed > 0:
        print("\nFAILURES:")
        for entry in per_source:
            if not entry["passed"]:
                hard = [m for m in entry["missing_fields"] if not m.startswith("ADVISORY")]
                if hard:
                    print(f"  [{entry['bucket']}] {entry['path']}")
                    for m in hard:
                        print(f"      missing: {m}")

        advisory_list = [
            entry for entry in per_source
            if entry.get("advisory") or any(
                m.startswith("ADVISORY") for m in entry.get("missing_fields", [])
            )
        ]
        if advisory_list:
            print("\nADVISORY (non-blocking, backfill recommended):")
            for entry in advisory_list:
                advisories = entry.get("advisory") or [
                    m for m in entry.get("missing_fields", []) if m.startswith("ADVISORY")
                ]
                print(f"  {entry['path']}")
                for a in advisories:
                    print(f"      {a}")

    return 1 if failed > 0 else 0


if __name__ == "__main__":
    sys.exit(main())
